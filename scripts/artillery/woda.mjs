// Marks generated artillery stations that fall on sea or big lakes (Natural Earth 1:10m land/lakes) as a bitmask,
// the 7th field of each city in public/artillery/swiat.json (owner, 1 Nov 2026: coastal cities like Istanbul).
// Download first: https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_land.geojson
// and ne_10m_lakes.geojson. Usage: node --experimental-strip-types scripts/artillery/woda.mjs land.geojson lakes.geojson
// Then re-import docs/sql/artillery-swiat-dane.sql (written here too).
import fs from "node:fs";
const G = await import("../../src/artillery/generator.ts");
const [landFile, lakesFile] = process.argv.slice(2);
const BAND = 10; // bands per degree of latitude
function index(file) {
  const bands = new Map();
  for (const f of JSON.parse(fs.readFileSync(file)).features) {
    const g = f.geometry, polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
    for (const poly of polys)
      for (const ring of poly)
        for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
          const [x1, y1] = ring[i], [x2, y2] = ring[j];
          const lo = Math.floor(Math.min(y1, y2) * BAND), hi = Math.floor(Math.max(y1, y2) * BAND);
          for (let b = lo; b <= hi; b++) {
            let l = bands.get(b);
            if (!l) bands.set(b, (l = []));
            l.push(x1, y1, x2, y2);
          }
        }
  }
  return (lat, lon) => {
    const l = bands.get(Math.floor(lat * BAND)) ?? [];
    let c = false;
    for (let i = 0; i < l.length; i += 4) {
      const x1 = l[i], y1 = l[i + 1], x2 = l[i + 2], y2 = l[i + 3];
      if (y1 > lat !== y2 > lat && lon < ((x2 - x1) * (lat - y1)) / (y2 - y1) + x1) c = !c;
    }
    return c;
  };
}
const land = index(landFile), lakes = index(lakesFile);
const swiat = JSON.parse(fs.readFileSync("public/artillery/swiat.json"));
let masked = 0, cities = 0;
for (const m of swiat.miasta) {
  // Gates are pulled in towards the districts that are kept (7 km rule), so the mask is repeated until it settles.
  // Bits count candidates (generator `idx`), not kept stations.
  let woda = 0;
  for (let runda = 0; runda < 6; runda++) {
    const s = G.generujSiec([m[0], m[1], m[2], m[3], m[4], m[5], woda], []);
    let nowa = woda;
    for (const st of s.stacje) {
      if (!land(st.lat, st.lon) || lakes(st.lat, st.lon)) nowa |= 2 ** st.kand;
    }
    if (nowa === woda) break;
    woda = nowa;
  }
  m.length = 6;
  if (woda) {
    m.push(woda);
    for (let b = 0; b < 31; b++) if ((woda >> b) & 1) masked++;
    cities++;
  }
}
fs.writeFileSync("public/artillery/swiat.json", JSON.stringify(swiat));
const q = (s) => "'" + String(s).replaceAll("'", "''") + "'";
let sql = "-- Generated by scripts/artillery/swiat.py + woda.mjs. Replaces the world list of the generated artillery.\nbegin;\ndelete from public.ma_miasta;\ndelete from public.ma_lotniska;\n";
for (let i = 0; i < swiat.miasta.length; i += 500)
  sql += "insert into public.ma_miasta(id,name,cc,lat,lon,pop,woda) values\n" + swiat.miasta.slice(i, i + 500).map((r) => `(${r[0]},${q(r[1])},${q(r[2])},${r[3]},${r[4]},${r[5]},${r[6] ?? 0})`).join(",\n") + ";\n";
for (let i = 0; i < swiat.lotniska.length; i += 500)
  sql += "insert into public.ma_lotniska(id,name,lat,lon) values\n" + swiat.lotniska.slice(i, i + 500).map((r) => `(${q(r[0])},${q(r[1])},${r[2]},${r[3]})`).join(",\n") + ";\n";
fs.writeFileSync("docs/sql/artillery-swiat-dane.sql", sql + "commit;\n");
console.log(`${masked} stations on water left out in ${cities} of ${swiat.miasta.length} cities`);
