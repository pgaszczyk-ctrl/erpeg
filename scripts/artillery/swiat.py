#!/usr/bin/env python3
"""World list for the generated municipal artillery (owner, 1 Nov 2026: every city of similar size, worldwide).

Inputs (download first, they are not kept in the repo):
  cities500.json  – GeoNames cities ≥ 500 people with population, mirror:
                    https://raw.githubusercontent.com/lmfmaier/cities-json/master/cities500.json
  airports.csv    – OurAirports: https://raw.githubusercontent.com/davidmegginson/ourairports-data/main/airports.csv
Usage: python3 -I scripts/artillery/swiat.py cities500.json airports.csv
Writes public/artillery/swiat.json and docs/sql/artillery-swiat-dane.sql.
GeoNames lists city districts separately (Mokotów, Praga Południe…): a place inside a bigger kept city's
outer ring is dropped, so a district never gets a network of its own.
Numbers must match src/artillery/generator.ts (MIASTO_MIN, promien).
"""
import csv, json, math, sys

MIASTO_MIN = 100_000
def promien(pop): return 9.5 * math.sqrt(pop)          # metres, ~built-up radius
def dist(a, b):
    lat = math.radians((a[0] + b[0]) / 2)
    return math.hypot((b[1] - a[1]) * 111320 * math.cos(lat), (b[0] - a[0]) * 111132)

cities = [c for c in json.load(open(sys.argv[1])) if int(c['pop'] or 0) >= MIASTO_MIN]
cities.sort(key=lambda c: -int(c['pop']))
kept, grid = [], {}
def cell(lat, lon): return (int(math.floor(lat)), int(math.floor(lon)))
for c in cities:
    lat, lon, pop = round(float(c['lat']), 4), round(float(c['lon']), 4), int(c['pop'])
    ok = True
    cy, cx = cell(lat, lon)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            for k in grid.get((cy + dy, cx + dx), []):
                if dist((lat, lon), (k[3], k[4])) < promien(k[5]):
                    ok = False; break
            if not ok: break
        if not ok: break
    if not ok: continue
    row = [int(c['id']), c['name'], c['country'], lat, lon, pop]
    kept.append(row); grid.setdefault((cy, cx), []).append(row)

ports = []
for r in csv.DictReader(open(sys.argv[2], encoding='utf-8')):
    if r['type'] in ('large_airport', 'medium_airport') and r['scheduled_service'] == 'yes':
        ports.append([r['ident'], r['name'], round(float(r['latitude_deg']), 5), round(float(r['longitude_deg']), 5)])
ports.sort()
json.dump({'wersja': 1, 'miasta': kept, 'lotniska': ports}, open('public/artillery/swiat.json', 'w'), ensure_ascii=False, separators=(',', ':'))

q = lambda s: "'" + str(s).replace("'", "''") + "'"
with open('docs/sql/artillery-swiat-dane.sql', 'w') as f:
    f.write('-- Generated by scripts/artillery/swiat.py. Replaces the world list of the generated artillery.\nbegin;\ndelete from public.ma_miasta;\ndelete from public.ma_lotniska;\n')
    for i in range(0, len(kept), 500):
        f.write('insert into public.ma_miasta(id,name,cc,lat,lon,pop) values\n' + ',\n'.join(f'({r[0]},{q(r[1])},{q(r[2])},{r[3]},{r[4]},{r[5]})' for r in kept[i:i+500]) + ';\n')
    for i in range(0, len(ports), 500):
        f.write('insert into public.ma_lotniska(id,name,lat,lon) values\n' + ',\n'.join(f'({q(r[0])},{q(r[1])},{r[2]},{r[3]})' for r in ports[i:i+500]) + ';\n')
    f.write('commit;\n')
print(len(cities), 'places ≥', MIASTO_MIN, '→', len(kept), 'cities;', len(ports), 'airports')
