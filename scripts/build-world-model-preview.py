"""Publish the approved G008 preview using the repository's actual GLB files."""
import ast
from pathlib import Path
import shutil

root = Path(__file__).resolve().parents[1]
pkg = root / 'docs/poczta/od-grafika/44_ruchomy_swiat_3d'
src = pkg / '44_ruchome_3d/src'
# Reuse the artist's reviewed UI and rigid-animation renderer without rebuilding models.
module = ast.parse((src / 'build_viewer.py').read_text())
html = next(ast.literal_eval(n.value) for n in module.body
            if isinstance(n, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'html' for t in n.targets))
start = html.index('<p>')
end = html.index('</p>', start) + 4
html = html[:start] + '<p>28 zaakceptowanych modeli G008: przeciwnicy, mieszkańcy i pies. Wybierz postać, animację i obrót. To podgląd zasobów — podłączenie tych modeli w świecie gry jest jeszcze do wykonania.</p>' + html[end:]
html = html.replace('Samodzielny podgląd offline.', 'Podgląd na serwerze testowym. Modele pobierane z tej samej paczki GLB, którą otrzymała gra.')
html = html.replace('Obejrzyj dołączoną planszę i animacje GIF.', 'Spróbuj przeglądarki z obsługą WebGL.')
html = html.replace('<p id="error"></p>', '<p id="error" role="status">Ładowanie modeli…</p>')
html += '<script src="modele-swiata.js"></script></html>\n'
bootstrap = '''// Generated by scripts/build-world-model-preview.py; model renderer from the approved artist package.
(async () => {
 const status = document.getElementById('error');
 try {
  async function get(path, json = false) {
   const response = await fetch(new URL(path, location.href));
   if (!response.ok) throw new Error(`Nie udało się pobrać ${path} (${response.status})`);
   return json ? response.json() : new Uint8Array(await response.arrayBuffer());
  }
  const manifest = await get('modele/swiat44/manifest.json', true);
  const paths = [['straznik', 'modele/wzorzec-chibi.glb'], ...Object.entries(manifest).map(([id, entry]) => [id, entry.file.replace(/^\\//, '')])];
  const ASSETS = Object.fromEntries(await Promise.all(paths.map(async ([id, path]) => {
   const bytes = await get(path);
   let binary = '';
   for (let i = 0; i < bytes.length; i += 16384) binary += String.fromCharCode(...bytes.subarray(i, i + 16384));
   return [id, btoa(binary)];
  })));
  status.textContent = '';
'''
js = bootstrap + (src / 'viewer.js').read_text() + '''
 } catch (error) {
  status.textContent = `Nie udało się uruchomić podglądu: ${error.message}. Odśwież stronę lub spróbuj przeglądarki z WebGL.`;
  console.error(error);
 }
})();
'''
(root / 'public/modele-swiata.html').write_text(html)
(root / 'public/modele-swiata.js').write_text(js)
shutil.copyfile(pkg / 'referencja/straznik_chibi_wzorzec.glb', root / 'public/modele/wzorzec-chibi.glb')
print('Published preview: 28 models + reference guard')
