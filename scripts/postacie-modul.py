#!/usr/bin/env python3
"""Modular heroes (artist pack „postacie modułowe v6.1”, orders 41-G001/41-G002): a head and a body glued at the neck.

Reads scripts/modul-zrodla/ (the artist's 3×3 sheets of 64 px – rows front / left profile / back, columns
step A / standing / step B – their masks and manifest.json) and writes
  public/postacie/modul/{glowy,glowy_maska,ciala,ciala_maska}.png  – the 20 sheets side by side (3840×192)
  src/content/modulDane.ts                                         – anchors per direction, gender, reference colours
Masks are the artist's: red/green = clothes, blue = skin, yellow = hair/beard/brows. The reference colour of
each material (the 75th-percentile brightest pixel of the standing front frame) lets recolouring keep the
material's own shading – dark hair turns into a dark-to-light blond, not a black one.
Run: python3 scripts/postacie-modul.py
"""
import json, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
Z = os.path.join(ROOT, 'scripts', 'modul-zrodla')
OUT = os.path.join(ROOT, 'public', 'postacie', 'modul')
m = json.load(open(os.path.join(Z, 'manifest.json')))
NAZWY = {'01': 'Warkocze', '02': 'Kowal', '03': 'Pilotka', '04': 'Profesor', '05': 'Kucharka', '06': 'Ogrodniczka',
         '07': 'Maszynista', '08': 'Kurierka', '09': 'Wynalazca', '10': 'Karczmarz', '11': 'Czarodziej', '12': 'Zwiadowca',
         '13': 'Dżentelmen', '14': 'Podróżnik', '15': 'Gospodyni', '16': 'Strażnik', '17': 'Rudobrody', '18': 'Łuczniczka',
         '19': 'Listonosz', '20': 'Mechanik'}
KIER = ('front', 'left', 'back')
KOLORY = {'skora': (0, 0, 255), 'wlosy': (255, 255, 0), 'u1': (255, 0, 0), 'u2': (0, 255, 0)}
wiek = {h['id']: h.get('wiek', 'dorosly') for h in m['heads']}


def ref(sheet, mask, kolor):
    """Reference colour of a material: the 75th-percentile brightest pixel of the standing front frame (cell 1,0)."""
    px, mp = sheet.load(), mask.load()
    cs = [px[x, y][:3] for x in range(64, 128) for y in range(64)
          if px[x, y][3] and mp[x, y][3] and mp[x, y][:3] == kolor]
    if len(cs) < 6:
        return None
    cs.sort(key=lambda c: max(c))
    return list(cs[len(cs) * 3 // 4])


strips = {k: Image.new('RGBA', (192 * 20, 192), (0, 0, 0, 0)) for k in ('glowy', 'glowy_maska', 'ciala', 'ciala_maska')}
postacie = []
for i, c in enumerate(m['characters']):
    base = c['filename_base']
    sh = {
        'glowy': Image.open(os.path.join(Z, 'sheets_192', f'{base}_head_3x3.png')).convert('RGBA'),
        'glowy_maska': Image.open(os.path.join(Z, 'mask_sheets_192', f'{base}_head_mask_3x3.png')).convert('RGBA'),
        'ciala': Image.open(os.path.join(Z, 'sheets_192', f'{base}_body_3x3.png')).convert('RGBA'),
        'ciala_maska': Image.open(os.path.join(Z, 'mask_sheets_192', f'{base}_body_mask_3x3.png')).convert('RGBA'),
    }
    for k, im in sh.items():
        assert im.size == (192, 192), (base, k, im.size)
        strips[k].paste(im, (i * 192, 0))
    kier = []
    for dn in KIER:
        d = c['directions'][dn]
        kier.append({'mx': d['head_mount']['x'], 'my': d['head_mount']['y'], 'nx': d['neck']['x'], 'ny': d['neck']['y']})
    postacie.append({
        'id': c['id'][:2], 'nazwa': NAZWY[c['id'][:2]], 'plec': c['plec'], 'wiek': wiek.get(c['id'], 'dorosly'), 'kier': kier,
        'glowa': {k: ref(sh['glowy'], sh['glowy_maska'], KOLORY[k]) for k in ('skora', 'wlosy')},
        'cialo': {k: ref(sh['ciala'], sh['ciala_maska'], KOLORY[k]) for k in ('skora', 'u1', 'u2')},
    })
os.makedirs(OUT, exist_ok=True)
for k, im in strips.items():
    im.save(os.path.join(OUT, k + '.png'), optimize=True)
ts = ['// Generated by scripts/postacie-modul.py – do not edit by hand.',
      '/** Where head and body meet in one direction (64 px cell): the head\'s mount point (mx, my) and the body\'s neck (nx, ny). */',
      'export interface KierunekModul { mx: number; my: number; nx: number; ny: number }',
      '/** Reference colour of a material in this part (null = the part has none of it). */',
      'export type Wzorzec = number[] | null;',
      '/** One of the 20 characters: its head and its body, 3 directions (front, left profile, back). */',
      "export interface PostacModul { id: string; nazwa: string; plec: 'k' | 'm'; wiek: string; kier: KierunekModul[]; glowa: { skora: Wzorzec; wlosy: Wzorzec }; cialo: { skora: Wzorzec; u1: Wzorzec; u2: Wzorzec } }",
      'export const POSTACIE_MODUL: PostacModul[] = ' + json.dumps(postacie, ensure_ascii=False) + ';', '']
open(os.path.join(ROOT, 'src', 'content', 'modulDane.ts'), 'w').write('\n'.join(ts))
print('postaci', len(postacie), 'bez wlosow:', [p['id'] for p in postacie if not p['glowa']['wlosy']])
