const zwykle = (s: string) => s.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
const zbior = new Set(MIASTA_Z_METREM.map(zwykle));
/** Smaller namesakes of metro cities (GeoNames ids) – no metro there. */
const IMIENNICY = new Set([1793743, 1810820, 1796989]);
/** Does this city (country code + name from swiat.json, and its id when known) have a metro? */
export const maMetro = (cc: string, nazwa: string, id?: number) =>
  !(id !== undefined && IMIENNICY.has(id)) && zbior.has(zwykle(`${cc}:${nazwa}`));
