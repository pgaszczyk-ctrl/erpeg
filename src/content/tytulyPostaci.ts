export const MAKS_NAZWY_POSTACI = 40;

export function losowaNazwaPostaci(plec: 'm' | 'k' = 'm'): string {
  const indeks = Math.random();
  const tytul = lang === 'pl'
    ? TYTULY_POLSKIE[Math.floor(indeks * TYTULY_POLSKIE.length)][plec === 'k' ? 1 : 0]
    : TYTULY_ANGIELSKIE[Math.floor(indeks * TYTULY_ANGIELSKIE.length)];
  return `${losoweImie(plec)} ${tytul}`;
}
